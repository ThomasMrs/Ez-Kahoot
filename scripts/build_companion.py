"""Build local MV3 runtimes and shared console assets. No third-party dependency."""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
EXTENSION = ROOT / "extension"
SHARED = ROOT / "public" / "shared"
MODULES = ("matching.js", "automation.js", "active-choice.js", "live-panel.js")


def classic_module(source):
    source = re.sub(r"^import[^\n]*\n", "", source, flags=re.M)
    source = re.sub(r"\bexport\s+(?=(?:function|const|let|class)\b)", "", source)
    if re.search(r"^\s*(?:import|export)\s", source, flags=re.M):
        raise ValueError("Unsupported module syntax in local companion source")
    return source


def build():
    SHARED.mkdir(exist_ok=True)
    for name in (*MODULES, "reader.js"):
        (SHARED / name).write_bytes((EXTENSION / name).read_bytes())
    sources = "\n".join(classic_module((EXTENSION / name).read_text()) for name in MODULES)
    reader = (EXTENSION / "reader.js").read_text().strip().removesuffix(";")
    runtime = "/* Generated by scripts/build_companion.py — thomas marsa */\n(() => {\n'use strict';\n" + sources
    runtime += "\nconst readPage = () => (" + reader + ");\n"
    runtime += """
globalThis.__ezKahootStart = quiz => {
  if (location.protocol !== 'https:' || !['kahoot.it','create.kahoot.it','play.kahoot.it'].includes(location.hostname)) return {ok:false};
  let panel;
  let disposed = false;
  let verifying = true;
  panel = mountLivePanel({quiz,readPage,decideAnswer:(loaded,capture)=>{
    const decision=decideAnswer(loaded,capture);
    return verifying && decision.status==='ready' ? {...decision,status:'waiting',targetIndexes:[],message:'Vérification de la partie…'} : decision;
  },
    activateAnswer:(capture,index)=>activateAnswer(capture,index,readPage),
    onRefresh:async ({quiz:loaded})=>{
      if (disposed || !panel?.host.isConnected) return;
      verifying = true;
      panel.refresh();
      try {
        const response = await chrome.runtime.sendMessage({type:'EZK_DISCOVER',knownQuizId:loaded?.id||''});
        if (disposed || !panel.host.isConnected) return;
        panel.setRevealedAnswer(response?.metadata?.revealedAnswer || null);
        const detected=response?.metadata?.quizId;
        if (detected && loaded?.id && detected.toLowerCase() !== loaded.id.toLowerCase()) panel.setQuiz(null);
        if (!response?.ok) { panel.setDiscoveryStatus(response?.error || 'Recherche du quiz indisponible.'); return; }
        const metadata=response.metadata||{};
        let next=response.quiz||(detected && loaded?.id && detected.toLowerCase() !== loaded.id.toLowerCase() ? null : loaded);
        const total=next?.questions?.length+(Number(next?.slideCount)||0)+(Number(next?.skippedCount)||0);
        if (metadata.questionCount && next && total !== metadata.questionCount) {
          panel.setQuiz(null);
          panel.setDiscoveryStatus('Le corrigé chargé ne correspond pas au nombre de questions de cette partie.');
          return;
        }
        if (response.quiz) panel.setQuiz(response.quiz);
        if (!next) panel.setDiscoveryStatus(metadata.quizId ? 'Chargement du corrigé…' : 'Cette page n’a pas transmis l’identifiant ni le corrigé du quiz.');
      } catch { panel.setDiscoveryStatus('Rouvre le panneau depuis l’extension à jour.'); }
      finally { verifying=false; if (!disposed && panel.host.isConnected) panel.refresh(); }
    }
  });
  panel.host.addEventListener('ez-live-dispose',()=>{disposed=true},{once:true});
  return {ok:true};
};
})();
"""
    (EXTENSION / "live-runtime.js").write_text(runtime)
    discovery = classic_module((EXTENSION / "discovery.js").read_text())
    (EXTENSION / "probe-runtime.js").write_text(
        "/* Generated by scripts/build_companion.py — metadata only */\n(() => {\n" + discovery + "\nreturn discoverQuizMetadata();\n})()\n"
    )
    print("Companion runtimes and console assets built.")


if __name__ == "__main__":
    build()
